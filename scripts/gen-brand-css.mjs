#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import palettes from '../site/src/lib/brand-palettes.json' with { type: 'json' }

// Both shells consume the same explicit sRGB shades, including without JS.
const variables = (p, color) => ({
  'brand-color': color,
  'brand-solid': p.solid, 'brand-on-solid': p.onSolid,
  'button-bg-primary': p.solid, 'button-text-primary': p.onSolid,
  'theme-primary': p.link, 'theme-secondary': p.muted, 'theme-accent': p.link,
  'theme-background': p.background, 'theme-text': p.text,
  'background-color': p.background, 'text-color': p.text,
  'topnav-background': p.background, 'topnav-text-color': p.text,
  'topnav-link-color': p.link, 'topnav-link-hover-color': p.text,
  'color-background-primary': p.background, 'color-background-secondary': p.surface,
  'color-background-border': p.border, 'color-api-background-hover': p.hover,
  'color-foreground-primary': p.text, 'color-foreground-secondary': p.muted,
  'color-foreground-muted': p.muted, 'color-link': p.link,
  'color-brand-primary': p.link, 'color-brand-content': p.link,
  'color-inline-code-background': p.surface,
  'lt-color-bg': p.background, 'lt-color-bg-secondary': p.surface,
  'lt-color-bg-hover': p.hover, 'lt-color-fg': p.text,
  'lt-color-fg-secondary': p.muted, 'lt-color-fg-muted': p.muted,
  'lt-color-border': p.border, 'lt-color-accent': p.link,
  'lt-color-link': p.link, 'lt-color-link-visited': p.link,
  'lt-color-code-bg': p.surface,
})
const declarations = (p, color, mode) => `color-scheme: ${mode};\n${Object.entries(variables(p, color)).map(([key, value]) => `  --${key}: ${value};`).join('\n')}`
let css = '/* Generated by scripts/gen-brand-css.mjs from brand-palettes.json. */\n'
for (const [language, p] of Object.entries(palettes)) {
  const selector = `html[data-brand="${language}"]`
  css += `${selector} {\n  ${declarations(p.light, p.color, 'light')}\n}\n`
  css += `${selector}[data-theme-mode="dark"], ${selector}[data-theme="dark"] {\n  ${declarations(p.dark, p.color, 'dark')}\n}\n`
  css += `@media (prefers-color-scheme: dark) {\n  ${selector}:not([data-theme-mode]):not([data-theme="light"]) {\n  ${declarations(p.dark, p.color, 'dark')}\n  }\n}\n`
}
for (const path of ['site/src/styles/brand.css', 'site/public/_shell/brand.css']) {
  const file = resolve(path)
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== css) throw new Error(`Stale branding CSS: ${path}`)
  } else writeFileSync(file, css)
}
console.log(`Brand CSS: ${Object.keys(palettes).length} language palettes`)
